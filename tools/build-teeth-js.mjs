/* Emits assets/data/teeth-data.js from assets/data/teeth.json.

   The site has to open straight off disk (file://), where fetch() is blocked,
   so the tooth map is inlined as a plain script exactly the way
   assets/locales/locales.js is. Re-run this after tools/build-teeth-map.py.

   node tools/build-teeth-js.mjs */

import { readFileSync, writeFileSync } from "node:fs";

const SRC = "assets/data/teeth.json";
const OUT = "assets/data/teeth-data.js";

const data = JSON.parse(readFileSync(SRC, "utf8"));
const teeth = data.teeth;

const upper = teeth.filter(t => t.arch === "upper").length;
const lower = teeth.filter(t => t.arch === "lower").length;

if (teeth.length !== 32) {
  console.warn(`! expected 32 teeth, found ${teeth.length} — the calendar needs 31 for a long month`);
}

const banner =
  "/* generated by tools/build-teeth-js.mjs from assets/data/teeth.json — do not hand-edit.\n"
  + "   Inlined so the booking page runs from file://, where fetch() is blocked.\n"
  + `   ${upper} upper + ${lower} lower = ${teeth.length} teeth, as percentages of the stage image. */\n`;

writeFileSync(OUT, (banner + `window.DH_TEETH = ${JSON.stringify(teeth)};\n`).replace(/\n/g, "\r\n"));

console.log(`${OUT} written — ${upper} upper + ${lower} lower = ${teeth.length} teeth`);
